"""
Module: streamlit_app.pages.risk_results
Page 3: Risk Results — Ranked 1-Year Incident Comorbidity Deliverable.
"""

import streamlit as st
import pandas as pd

from streamlit_app.components.page_header import render_page_header
from streamlit_app.components.risk_card import render_risk_card
from streamlit_app.components.empty_state import render_empty_assessment_state
from streamlit_app.state.session import get_patient, get_result
from streamlit_app.disease_metadata.registry import get_condition_info


def render():
    render_page_header(
        title="Risk Results",
        subtitle="Ranked 1-year incident comorbidity predictions generated by calibrated multi-model stacked ensemble."
    )

    result = get_result()
    patient = get_patient()

    if result is None or patient is None:
        render_empty_assessment_state(
            title="No Active Patient Assessment",
            message="No comorbidity risk results are available yet. Please complete a patient assessment to generate predictions.",
            button_label="Start Patient Assessment"
        )
        return

    # 1. Summary Header (Section 15)
    gender_str = "male" if str(patient.gender).lower() in ["m", "male", "8507"] else "female"
    n_existing = len(patient.current_condition_ids)
    n_elevated = len([p for p in result.all_candidate_predictions if p.is_flagged_elevated_risk])
    n_masked = len(result.already_diagnosed_conditions)

    st.markdown(
        f"""
        <div style="background-color: #FFFFFF; border: 1px solid #E2E8F0; border-radius: 6px; padding: 0.90rem 1.25rem; margin-bottom: 1.25rem;">
            <span style="font-size: 1.05rem; font-weight: 700; color: #1E3A8A;">
                {int(patient.age)}-year-old {gender_str}
            </span>
            <span style="color: #64748B; margin: 0 8px;">&bull;</span>
            <span style="font-size: 0.92rem; color: #334155; font-weight: 600;">
                {n_existing} documented condition{'s' if n_existing != 1 else ''}
            </span>
            <span style="color: #64748B; margin: 0 8px;">&bull;</span>
            <span style="font-size: 0.92rem; color: #334155;">
                41 conditions evaluated
            </span>
            <span style="color: #64748B; margin: 0 8px;">&bull;</span>
            <span style="font-size: 0.92rem; color: {'#DC2626' if n_elevated > 0 else '#1E3A8A'}; font-weight: 700;">
                {n_elevated} flagged elevated
            </span>
        </div>
        """,
        unsafe_allow_html=True
    )

    # 2. Existing-Diagnosis Masking Disclosure (Section 18)
    if result.already_diagnosed_conditions:
        with st.expander(f"Existing conditions: {n_masked} documented conditions excluded from incident-risk predictions", expanded=False):
            st.markdown(
                '<p style="color: #475569; font-size: 0.88rem; line-height: 1.45; margin-bottom: 0.5rem;">'
                f'<strong>{n_masked} documented conditions</strong> were excluded from incident-risk '
                'predictions because they are already present in the patient record:'
                '</p>',
                unsafe_allow_html=True
            )
            masked_chips = []
            for item in result.already_diagnosed_conditions:
                cid = item.get("concept_id")
                info = get_condition_info(cid)
                masked_chips.append(
                    f'<span style="display: inline-block; background-color: #F1F5F9; border: 1px solid #CBD5E1; '
                    f'border-radius: 4px; padding: 3px 8px; font-size: 0.82rem; margin: 2px 4px 4px 0; color: #334155; font-weight: 500;">'
                    f'{info.canonical_term} (OMOP {cid})</span>'
                )
            st.markdown("".join(masked_chips), unsafe_allow_html=True)

    # 3. Potentially Elevated Risks (Ranked Risk Cards)
    st.markdown("### Potentially Elevated Risks")
    st.markdown(
        '<p class="page-subtitle">'
        'Conditions ranked by calibrated 1-year probability. Click <em>View explanation →</em> to inspect clinical drivers and model consensus.'
        '</p>',
        unsafe_allow_html=True
    )

    for rank_idx, item in enumerate(result.top_ranked_predictions, 1):
        render_risk_card(rank=rank_idx, item=item)

    # 4. Collapsible Full 41-Target Matrix
    st.markdown("<hr />", unsafe_allow_html=True)
    with st.expander(f"View full 41-target evaluation table ({len(result.all_candidate_predictions)} candidate conditions)", expanded=False):
        st.markdown(
            '<p style="color: #64748B; font-size: 0.86rem; margin-bottom: 0.5rem;">'
            'Complete calibrated risk estimates for all unmasked comorbidities in the target vocabulary.'
            '</p>',
            unsafe_allow_html=True
        )
        df_full = result.to_dataframe(include_all=True)
        st.dataframe(df_full, use_container_width=True, hide_index=True)

    # Navigation buttons
    col_back, col_exp = st.columns([0.5, 0.5])
    with col_back:
        if st.button("← Modify Patient Assessment", use_container_width=True):
            from streamlit_app.navigation.router import PAGE_ASSESSMENT
            st.switch_page(PAGE_ASSESSMENT)
    with col_exp:
        if st.button("Explore Detailed Explainability →", type="primary", use_container_width=True):
            from streamlit_app.navigation.router import PAGE_EXPLAINABILITY
            st.switch_page(PAGE_EXPLAINABILITY)


if __name__ == "__main__":
    render()