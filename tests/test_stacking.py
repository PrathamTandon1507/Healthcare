def test_patient_kfold_splits_strict_isolation():
    """
    CRITICAL TEST: Verifies that patient-level K-fold splitting achieves
    ZERO patient overlap between training folds and OOF evaluation folds.
    """
    # 20 unique patients, each having 1 to 5 landmark rows
    rng = np.random.RandomState(42)
    person_ids = []
    for pid in range(1001, 1021):
        n_rows = rng.randint(1, 6)
        person_ids.extend([pid] * n_rows)
    person_ids = np.array(person_ids)

    n_samples = len(person_ids)
    splits = build_patient_kfold_splits(person_ids, n_splits=5, random_seed=42)

    assert len(splits) == 5

    all_val_indices = []
    for fold_idx, (tr_idx, val_idx) in enumerate(splits):
        # 1. Row index disjointness
        overlap_rows = set(tr_idx).intersection(set(val_idx))
        assert len(overlap_rows) == 0, f"Row index overlap in fold {fold_idx}!"

        # 2. Patient ID strict disjointness
        tr_patients = set(person_ids[tr_idx])
        val_patients = set(person_ids[val_idx])
        overlap_patients = tr_patients.intersection(val_patients)
        assert len(overlap_patients) == 0, f"PATIENT LEAKAGE in fold {fold_idx}: patients {overlap_patients} in both train and val!"

        # 3. Sum of lengths equals total
        assert len(tr_idx) + len(val_idx) == n_samples
        all_val_indices.extend(val_idx)

    # 4. Concatenation of all OOF indices covers exactly all rows once
    assert len(all_val_indices) == n_samples
    assert set(all_val_indices) == set(range(n_samples))


def test_row_id_bookkeeping_no_self_training():
    """
    CRITICAL TEST: Proves via row-ID and patient-ID bookkeeping that NO row's
    OOF prediction was generated by a model trained on that row or patient.
    """
    person_ids = np.array([1, 1, 2, 2, 3, 4, 5, 5, 6, 7, 8, 8, 9, 10])
    splits = build_patient_kfold_splits(person_ids, n_splits=3, random_seed=42)

    for fold_idx, (tr_idx, val_idx) in enumerate(splits):
        for val_row in val_idx:
            val_pt = person_ids[val_row]
            # Verify val_row is not in tr_idx
            assert val_row not in tr_idx
            # Verify no rows belonging to val_pt are in tr_idx
            for tr_row in tr_idx:
                assert person_ids[tr_row] != val_pt, f"Row {val_row} (Patient {val_pt}) evaluated by model trained on Row {tr_row} (Same Patient)!"


def test_train_single_stacked_ensemble_execution():
    """
    Verifies end-to-end execution of train_single_stacked_ensemble on dummy clinical data.
    """
    np.random.seed(42)
    n_samples = 150
    n_features = 5
    feature_names = ["age_at_landmark", "total_prior_condition_count", "prior_obs_years", "feat_a", "feat_b"]

    person_ids = np.repeat(np.arange(30), 5)  # 30 patients, 5 rows each
    X = np.random.randn(n_samples, n_features).astype(np.float32)
    y = ((X[:, 0] + X[:, 3]) > 0.5).astype(np.int32)

    lr_cfg = {"C": 1.0, "class_weight": "balanced"}
    rf_cfg = {"n_estimators": 10, "max_depth": 3, "min_samples_leaf": 2, "max_features": "sqrt", "class_weight": "balanced"}
    xgb_cfg = {"n_estimators": 10, "max_depth": 3, "learning_rate": 0.1, "reg_lambda": 1.0}

    stack_model, oof_matrix, meta = train_single_stacked_ensemble(
        X_train=X,
        y_train=y,
        train_person_ids=person_ids,
        feature_names=feature_names,
        target_cid=201826,
        lr_config=lr_cfg,
        rf_config=rf_cfg,
        xgb_config=xgb_cfg,
        n_splits=3,
        device="cpu",
        random_seed=42,
        n_jobs=1
    )

    assert stack_model is not None
    assert oof_matrix.shape == (n_samples, 3)
    assert np.all(oof_matrix >= 0.0) and np.all(oof_matrix <= 1.0)
    assert "meta_weights" in meta
    assert "weight_lr" in meta["meta_weights"]
    assert "weight_rf" in meta["meta_weights"]
    assert "weight_xgb" in meta["meta_weights"]

    # Inference test
    probs = stack_model.predict_proba(X)
    assert probs.shape == (n_samples, 2)
    assert np.all(probs >= 0.0) and np.all(probs <= 1.0)
    assert np.allclose(np.sum(probs, axis=1), 1.0)


